"""Shared pieces for story-quest builders written after Filter Coffee (sq_002): the camera shots for a
person who walks up to the driver's window, the voice script, the ui.csv rows and the line checks.

The shots follow the Nov 28 lessons in AGENTS.md: everything that walks up to the driver uses the
mark "beside:<role>" (their own side of the auto) and every shot of them is framed from AHEAD on
THEIR side, so the auto is never between the lens and the speaker, whichever side the player stops.
"""
import csv
import io
from pathlib import Path

from story_tres import ROOT

# Camera marks relative to the auto ([right, up, forward]).
FRONT = [2.1, 1.4, 7.2]  # front three-quarter of the auto, driver in view
FRONT_TO = [1.6, 1.35, 6.6]
AUTO_LOOK = [0.0, 1.05, 0.4]
WIDE = [0.0, 2.4, 10.5]
WIDE_LOOK = [0.0, 1.2, 0.0]
DRIVER_FACE = [0.0, 0.0, 1.4]  # someone at the window looks at the driver, so the lens ahead sees their face


def two_shot(role, fov=50):
    """From ahead on the person's side: the auto with them at the driver's window."""
    return {"eye": {"from": "role:" + role, "dist": 1.0, "side": 4.4, "up": 1.7, "ahead": True}, "look": "role:" + role,
            "fov": fov}


def walking(role, fov=56):
    """Watching them walk to the auto, from off to the side of their path."""
    return {"eye": {"from": "role:" + role, "dist": 1.6, "side": 4.6, "up": 1.8, "ahead": True}, "look": "role:" + role,
            "fov": fov}


def close(role, fov=40, side=2.6, dist=0.6):
    """The person standing by the driver, filmed from ahead of the auto on their side."""
    return {"eye": {"from": "role:" + role, "dist": dist, "side": side, "up": 1.55, "ahead": True}, "look": "role:" + role,
            "fov": fov}


def street(role, fov=60):
    """The person where they stand, the road side behind the lens."""
    return {"eye": {"from": "role:" + role, "dist": 3.8, "side": 2.2, "up": 1.9}, "look": "role:" + role, "fov": fov}


def walk_up(role, line, line_at=0.6, anim="wave"):
    """They see the auto, call out and walk to the driver's side."""
    return [
        {"fade_in": 0.5, "cam": street(role), "act": {role: {"face": "auto", "anim": anim}}, "line": line,
         "line_at": line_at, "min_s": 1.6},
        {"cam": walking(role),
         "act": {role: {"to": "beside:" + role, "gait": "walk", "then": "talk", "face": DRIVER_FACE}},
         "wait": role, "min_s": 1.0, "max_s": 9.0},
    ]


def talk(role, line, fov=40, anim="talk"):
    return {"cam": close(role, fov), "act": {role: {"anim": anim, "face": DRIVER_FACE}}, "line": line}


def driver(line):
    return {"cam": {"eye": FRONT, "eye_to": FRONT_TO, "look": AUTO_LOOK, "fov": 46}, "line": line}


def two(role, line, fov=48, anim="talk"):
    return {"cam": two_shot(role, fov), "act": {role: {"anim": anim, "face": DRIVER_FACE}}, "line": line}


def hold_on(role, fov=46):
    """Ends a scene on the person at the window, held for the choice."""
    return {"cam": close(role, fov), "act": {role: {"anim": "idle", "face": DRIVER_FACE}}, "min_s": 0.6, "hold": True}


def back_to(role, spot, last_line=None):
    beat = {"cam": {"eye": WIDE, "look": WIDE_LOOK, "fov": 54},
            "act": {role: {"to": spot, "gait": "walk", "then": "idle", "face": "auto"}}, "min_s": 1.8, "fade_out": 0.5}
    if last_line:
        beat["line"] = last_line
    return beat


def csv_row(key, en, ta):
    buf = io.StringIO()
    csv.writer(buf, lineterminator="").writerow([key, en, ta])
    return buf.getvalue()


def update_ui_csv(strings, speaker_names, lines, retired=()):
    """Writes the quest's strings, speaker names and VO_<LINE> subtitle rows into translations/ui.csv."""
    path = ROOT / "translations/ui.csv"
    rows = path.read_text(encoding="utf-8").split("\n")
    want = dict(strings)
    for k, (en, ta) in speaker_names.items():
        want[k] = (en, ta)
    for lid, _spk, _tags, en, ta in lines:
        want["VO_" + lid.upper()] = (en, ta)
    kept = []
    seen = set()
    for r in rows:
        key = r.split(",", 1)[0]
        if key in retired:
            continue
        if key in want:
            if key in seen:
                continue
            seen.add(key)
            kept.append(csv_row(key, *want[key]))
            continue
        kept.append(r)
    while kept and kept[-1] == "":
        kept.pop()
    for key, (en, ta) in want.items():
        if key not in seen:
            kept.append(csv_row(key, en, ta))
    path.write_text("\n".join(kept) + "\n", encoding="utf-8")


def voice_script(path_name, title, num, builder, cast_notes, lines):
    out = [f'# SQ{num} "{title}": Voice Script', "",
           f"Written by `tools/quests/{builder}` (edit the lines there, not here). Generated by",
           "**Actions -> Generate quest voices** (Indic Parler-TTS, see `docs/voice/README.md`).",
           "Each bullet is one line: `id Speaker: [tags] Tamil / [tags] English`. Files land in",
           f"`assets/audio/voice/sq{num}/<id>_<ta|en>.ogg`. Subtitles: `VO_SQ{num}_*` in `translations/ui.csv`.", "",
           "## Cast"] + cast_notes + ["", "## Lines"]
    for lid, spk, tags, en, ta in lines:
        out.append(f"- {lid} {spk}: {tags} {ta} / {tags} {en}")
    (ROOT / "docs/voice" / path_name).write_text("\n".join(out) + "\n", encoding="utf-8")


def check_lines(lines, cutscenes, barks):
    """Every line id is unique, every id a scene or bark says exists, and every line is used."""
    ids = [line[0] for line in lines]
    assert len(ids) == len(set(ids)), "duplicate line id"
    used = set()
    for beats in cutscenes.values():
        for b in beats:
            if "line" in b:
                used.add(b["line"])
    for bk in barks.values():
        for v in bk.values():
            used.update(v if isinstance(v, list) else [v] if isinstance(v, str) else [])
    assert used <= set(ids), used - set(ids)
    assert set(ids) <= used, set(ids) - used
